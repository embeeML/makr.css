/**
 * Builds addons/legacy.css from the OLD helper.min.css so existing markup
 * keeps working on top of makr.css.
 *
 *   node scripts/make-legacy.mjs css-start/helper.min.css
 *
 * What it does:
 *  - drops every rule makr.css core now provides (grid, flex, d-*, text-*…)
 *  - drops theme-only rules (body.boxed, tt-col, the [class*="col-"] gutter bug)
 *  - swaps hard-coded colors for CSS variables (old hex kept as fallback)
 *  - fixes the invalid calc() in .text-lg … .text-xxxlg
 *  - wraps it all in @layer makr.legacy
 * The old breakpoints (576/768/992/1025/1400) are kept on purpose so old
 * pages look exactly as before.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src) { console.error('usage: node scripts/make-legacy.mjs path/to/helper.min.css'); process.exit(1); }

let css = readFileSync(src, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const core = readFileSync(join(root, 'dist', 'makr.css'), 'utf8');
const coreClasses = new Set([...core.matchAll(/\.([a-zA-Z][\w-]*)/g)].map((m) => m[1]));

// classes core supersedes even though the names differ slightly
const supersededPrefixes = [/^col(-|$)/, /^offset-/, /^order-/, /^row-cols-/, /^justify-content-/, /^align-(items|self|content)-/, /^row$/, /^no-gutters$/];

// ---- tiny parser: top-level rules + one level of @media ----------------
function parse(text) {
  const out = []; let i = 0;
  while (i < text.length) {
    const open = text.indexOf('{', i);
    if (open < 0) break;
    const head = text.slice(i, open).trim();
    if (head.startsWith('@media')) {
      let depth = 1, j = open + 1;
      while (depth && j < text.length) { if (text[j] === '{') depth++; else if (text[j] === '}') depth--; j++; }
      out.push({ media: head, rules: parse(text.slice(open + 1, j - 1)) });
      i = j;
    } else {
      const close = text.indexOf('}', open);
      out.push({ sel: head, body: text.slice(open + 1, close) });
      i = close + 1;
    }
  }
  return out;
}

const colorVar = (cls, hex) => {
  if (/(main|primary)/.test(cls)) return 'var(--color-primary)';
  const name = cls.replace(/^(a\.)?\.?(bg|text|link|border)(-(top|bottom|left|right))?-/, '');
  return `var(--legacy-${name}, ${hex})`;
};

let dropped = 0, kept = 0;
function keepRule(r) {
  const sel = r.sel;
  if (/body\.boxed|tt-col|\[class\*="col-"\]/.test(sel)) { dropped++; return null; }
  const classes = [...sel.matchAll(/\.([a-zA-Z][\w-]*)/g)].map((m) => m[1]);
  const allCovered = classes.length && classes.every((c) => coreClasses.has(c) || supersededPrefixes.some((p) => p.test(c)));
  if (allCovered) { dropped++; return null; }
  let body = r.body
    .replace(/calc\(100%\+([\d.]+vw)\)/g, 'calc(100% + $1)');
  const firstCls = (classes[0] || '');
  body = body.replace(/#[0-9a-fA-F]{3,6}\b/g, (hex) =>
    /^(bg|text|link|border)-/.test(firstCls) || /^a\.link/.test(sel) ? colorVar(firstCls, hex) : hex);
  kept++;
  return `${sel} { ${body.trim()} }`;
}

const blocks = parse(css);
let outCss = '';
for (const b of blocks) {
  if (b.media) {
    const inner = b.rules.map((r) => (r.sel !== undefined ? keepRule(r) : null)).filter(Boolean);
    if (inner.length) outCss += `${b.media.replace(/@media\(/, '@media (')} {\n  ${inner.join('\n  ')}\n}\n`;
  } else {
    const k = keepRule(b);
    if (k) outCss += k + '\n';
  }
}

const header = `/* ==========================================================================
   makr.css — LEGACY add-on (generated by scripts/make-legacy.mjs)
   Old helper.css class names for existing sites. New sites don't need it.
   Colors are variables: override e.g. --legacy-red, --legacy-dark-2 …
   ${kept} rules kept, ${dropped} dropped (now provided by makr.css core).
   ========================================================================== */
@layer makr.legacy {
`;
writeFileSync(join(root, 'addons', 'legacy.css'), header + outCss + '}\n');
console.log(`addons/legacy.css: kept ${kept}, dropped ${dropped}`);
